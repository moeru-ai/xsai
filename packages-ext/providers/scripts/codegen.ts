import type { Provider } from '../src/types'
import type { DeepPartial } from './merge'

import { computeDefaults, normalizeCatalog } from '../src/normalize'
import { merge } from './merge'

/** Exact subpaths of the package. They take precedence over provider subpaths. */
export const RESERVED_SUBPATHS = [
  'audio',
  'capabilities',
  'decide',
  'embed',
  'fetch',
  'full',
  'image',
  'index',
  'package.json',
  'text',
  'types',
]

const HEADER = '// Generated by `pnpm sync` from models.dev. Do not edit.'

/** A valid JS identifier in camelCase, prefixed with `_` when the ID starts with a digit. */
export const exportName = (id: string) => {
  const name = id
    .split(/[^a-z0-9]+/i)
    .filter(part => part !== '')
    .map((part, index) => index === 0 ? part : part.charAt(0).toUpperCase() + part.slice(1))
    .join('')
  return /^\d/.test(name) ? `_${name}` : name
}

export interface BuildOptions {
  extra: Provider[]
  overrides: Record<string, Override>
}

/** `defaults` replaces computed defaults per protocol; other fields deep-merge. */
export type Override = DeepPartial<Omit<Provider, 'defaults'>> & Pick<Provider, 'defaults'>

/** Strictly normalizes the catalog, applies overrides, adds extra providers, and checks IDs. */
export const buildProviders = (catalog: unknown, { extra, overrides }: BuildOptions): Provider[] => {
  const normalized = normalizeCatalog(catalog, { strict: true })

  for (const id of Object.keys(overrides)) {
    if (!Object.hasOwn(normalized, id))
      throw new Error(`Override for unknown provider: ${id}`)
  }
  for (const provider of extra) {
    if (Object.hasOwn(normalized, provider.id))
      throw new Error(`Extra provider clashes with models.dev: ${provider.id}`)
  }

  const providers = [
    ...Object.values(normalized).map((provider) => {
      if (!Object.hasOwn(overrides, provider.id))
        return provider
      const { defaults, ...patch } = overrides[provider.id]
      const merged = merge<Provider>(provider, patch)
      return { ...merged, defaults: defaults === undefined ? computeDefaults(merged.models) : { ...computeDefaults(merged.models), ...defaults } }
    }),
    ...extra,
  ].toSorted((a, b) => a.id.localeCompare(b.id))

  const names = new Map<string, string>()
  for (const { id } of providers) {
    if (!/^[a-z0-9][\w.-]*$/i.test(id))
      throw new Error(`Provider ID is not a valid subpath: ${id}`)
    if (RESERVED_SUBPATHS.includes(id))
      throw new Error(`Provider ID matches a reserved subpath: ${id}`)
    const name = exportName(id)
    const other = names.get(name)
    if (other !== undefined)
      throw new Error(`Providers ${other} and ${id} share the export name ${name}`)
    names.set(name, id)
  }

  return providers
}

/** Pretty-prints the provider but keeps each model on one line, so diffs stay per model. */
const renderObject = ({ models, ...provider }: Provider) => {
  const entries = Object.entries(models).map(([id, model]) => `    ${JSON.stringify(id)}: ${JSON.stringify(model)},`)
  const body = JSON.stringify({ ...provider, models: {} }, null, 2)
  return entries.length === 0
    ? body
    : body.replace('"models": {}', ['"models": {', ...entries, '  }'].join('\n'))
}

export const renderProvider = (provider: Provider) => {
  const ids = Object.keys(provider.models)
  const models = ids.length === 0 ? 'never' : ids.map(id => JSON.stringify(id)).join(' | ')
  return [
    HEADER,
    'import type { Provider } from \'../types\'',
    `export const ${exportName(provider.id)}: Provider<${models}> = ${renderObject(provider)}`,
  ].join('\n\n').concat('\n')
}

export const renderFull = (providers: Provider[]) => [
  HEADER,
  [
    'import type { Provider } from \'./types\'',
    '',
    ...providers.map(({ id }) => `import { ${exportName(id)} } from './providers/${id}'`),
  ].join('\n'),
  [
    'export const providers: Record<string, Provider> = {',
    ...providers.map(({ id }) => `  ${JSON.stringify(id)}: ${exportName(id)},`),
    '}',
  ].join('\n'),
].join('\n\n').concat('\n')
