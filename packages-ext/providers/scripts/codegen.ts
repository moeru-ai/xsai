import type { CorrectionOptions } from '../src/corrections'
import type { Model, Provider } from '../src/types'

import { toRoutes } from '../src/client'
import { applyCorrections } from '../src/corrections'
import { normalizeCatalog } from '../src/normalize'

/** Exact subpaths of the package. They take precedence over provider subpaths. */
export const RESERVED_SUBPATHS = [
  'capabilities',
  'create',
  'fetch',
  'full',
  'index',
  'models',
  'package.json',
  'types',
]

const HEADER = '// Generated by `pnpm sync` from models.dev. Do not edit.'

const SHARED_FIELDS = ['capabilities', 'cost', 'limit', 'modalities', 'routes'] as const

/** The part of a constant's declaration after its name. It also identifies the value. */
const sharedDeclaration = (field: string, value: unknown) => `Model['${field}'] = ${JSON.stringify(value)}`

/** Names the field values that repeat within a provider, in order of first use. */
const nameSharedValues = (models: Model[]) => {
  const counts = new Map<string, number>()
  for (const model of models) {
    for (const field of SHARED_FIELDS) {
      if (model[field] === undefined)
        continue
      const declaration = sharedDeclaration(field, model[field])
      counts.set(declaration, (counts.get(declaration) ?? 0) + 1)
    }
  }
  const repeated = [...counts].filter(([, count]) => count > 1)
  return new Map(repeated.map(([declaration], index) => [declaration, `_${index.toString(36)}`]))
}

const renderSharedModel = (model: Model, names: ReadonlyMap<string, string>) => {
  const fields = Object.entries(model)
    .filter(([, value]) => value !== undefined)
    .map(([key, value]) => {
      const rendered = names.get(sharedDeclaration(key, value)) ?? JSON.stringify(value)
      return `${JSON.stringify(key)}:${rendered}`
    })
  return `{${fields.join(',')}}`
}

/** A valid JS identifier in camelCase, prefixed with `_` when the ID starts with a digit. */
export const exportName = (id: string) => {
  const name = id
    .split(/[^a-z0-9]+/i)
    .filter(part => part !== '')
    .map((part, index) => index === 0 ? part : part.charAt(0).toUpperCase() + part.slice(1))
    .join('')
  return /^\d/.test(name) ? `_${name}` : name
}

/** The client factory name, such as `createOpenai` or `create302ai`. */
export const factoryName = (id: string) => {
  const name = exportName(id).replace(/^_/, '')
  return `create${name.charAt(0).toUpperCase()}${name.slice(1)}`
}

/** Strictly normalizes the catalog, applies corrections, leaves out models without a route, and checks IDs. */
export const buildProviders = (catalog: unknown, options: Omit<CorrectionOptions, 'strict'>): Provider[] => {
  const providers = Object.values(applyCorrections(normalizeCatalog(catalog, { strict: true }), { ...options, strict: true }))
    .map(provider => ({
      ...provider,
      models: Object.fromEntries(Object.entries(provider.models).filter(([, model]) => Object.keys(model.routes).length > 0)),
    }))

  const names = new Map<string, string>()
  for (const { id } of providers) {
    if (!/^[a-z0-9][\w.-]*$/i.test(id))
      throw new Error(`Provider ID is not a valid subpath: ${id}`)
    if (RESERVED_SUBPATHS.includes(id))
      throw new Error(`Provider ID matches a reserved subpath: ${id}`)
    const name = exportName(id)
    const other = names.get(name)
    if (other !== undefined)
      throw new Error(`Providers ${other} and ${id} share the export name ${name}`)
    names.set(name, id)
  }

  return providers
}

/** Pretty-prints an object but keeps each model on one line. */
const renderObject = <T>({ models, ...rest }: { models: Record<string, T> }, renderModel: (model: T) => string = model => JSON.stringify(model)) => {
  const entries = Object.entries(models).map(([id, model]) => `    ${JSON.stringify(id)}: ${renderModel(model)},`)
  const body = JSON.stringify({ ...rest, models: {} }, null, 2)
  return entries.length === 0
    ? body
    // A replacer function, because a model name can contain `$$`.
    : body.replace('"models": {}', () => ['"models": {', ...entries, '  }'].join('\n'))
}

const modelUnion = (provider: Provider) => {
  const ids = Object.keys(provider.models)
  return ids.length === 0 ? 'never' : ids.map(id => JSON.stringify(id)).join(' | ')
}

/** `src/models/<id>.ts`: all provider data, with no xsAI dependency. Field values that repeat within the provider become constants. */
export const renderModels = (provider: Provider) => {
  const names = nameSharedValues(Object.values(provider.models))
  return [
    HEADER,
    `import type { ${names.size === 0 ? '' : 'Model, '}Provider } from '../types'`,
    ...names.size === 0 ? [] : [[...names].map(([declaration, name]) => `const ${name}: ${declaration}`).join('\n')],
    `export const ${exportName(provider.id)}: Provider<${modelUnion(provider)}> = ${renderObject(provider, model => renderSharedModel(model, names))}`,
  ].join('\n\n').concat('\n')
}

/** `src/providers/<id>.ts`: a client factory and a default client, with routes only. */
export const renderClient = (provider: Provider) => [
  HEADER,
  [
    'import type { ProviderRoutes } from \'../client\'',
    'import type { ProviderOptions } from \'../types\'',
    '',
    'import { createClient } from \'../client\'',
  ].join('\n'),
  `type Model = ${modelUnion(provider)}`,
  `const routes: ProviderRoutes<Model> = ${renderObject(toRoutes(provider))}`,
  `export const ${factoryName(provider.id)} = (options?: ProviderOptions) => createClient(routes, options)`,
  `export const ${exportName(provider.id)} = /* @__PURE__ */ ${factoryName(provider.id)}()`,
].join('\n\n').concat('\n')

export const renderFull = (providers: Provider[]) => [
  HEADER,
  [
    'import type { Provider } from \'./types\'',
    '',
    ...providers.map(({ id }) => `import { ${exportName(id)} } from './models/${id}'`),
  ].join('\n'),
  [
    'export const providers: Record<string, Provider> = {',
    ...providers.map(({ id }) => `  ${JSON.stringify(id)}: ${exportName(id)},`),
    '}',
  ].join('\n'),
].join('\n\n').concat('\n')
